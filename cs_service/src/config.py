"""
Параметры движка. Одно место, откуда берутся все числа, которые потом будут
калиброваться на данных. Ничего не считает — только значения и их обоснование.

Правило: если число ПОДБИРАЕТСЯ — оно здесь, а не внутри формулы.
"""

from __future__ import annotations

from dataclasses import dataclass, fields

# ── Усадка по выборке ─────────────────────────────────────────────────────────
#
# _STATE, «ядро силы»: усадка по выборке ОБЯЗАТЕЛЬНА. lineup/map отдаёт
# частотный винрейт — он слеп к силе соперника и на короткой выборке шумит.
# Тянем его к априору по правилу эмпирического Байеса:
#
#     w = n / (n + lambda),   p_оценка = w·p_набл + (1 − w)·p_априор
#
# n      — сколько раундов пятёрка отыграла на ЭТОЙ стороне ЭТОЙ карты;
# lambda — сила априора в тех же единицах: «сколько раундов надо увидеть,
#          чтобы поверить наблюдению наполовину».
#
# Порядок величины lambda. Для биномиального наблюдения EB даёт
#     lambda = p(1−p) / Var(истинных винрейтов между пятёрками).
# p(1−p) ≈ 0.25; разброс истинного раундового винрейта между составами —
# порядка sd 0.05-0.07 → Var 0.0025-0.005 → lambda ≈ 50-100 раундов.
# Берём верх диапазона: недооценить разрыв безопаснее, чем выдумать его.
#
# ЭТО ДЕФОЛТ, А НЕ КАЛИБРОВКА. Точное значение — из бэктеста против
# закрывающей линии (ЭТАП 5). Пока бэктеста нет — держим консервативно.
LAMBDA_ROUNDS = 100.0

# Априор, когда по карте нет даже m_map: чистая монетка.
NEUTRAL_PRIOR = 0.5

# Если в срезе нет total_rounds, выборку оцениваем по числу карт:
# карта MR12 идёт ~23 раунда, значит ~11.5 на сторону.
ROUNDS_PER_MAP = 23.0

# Границы, за которые p_round не выпускаем ни при какой комбинации входов.
# Симулятор считает и дальше, но за этими границами это уже не матч, а описка
# в данных. Границы симметричны относительно 0.5 — иначе сломается
# комплементарность p_A + p_B = 1.
P_MIN, P_MAX = 0.20, 0.80


# ── Отложенное: держим явным нулём, а не молчанием ────────────────────────────
#
# GAMMA_FORM     — вес формы игроков (gamma·dForm). Решение штаба: на старте
#                  не подключать, слагаемое отсутствует в расчёте.
# DELTA_MOMENTUM — остаток момента сверх экономики из формулы _STATE. На
#                  старте 0.
# SIM_DELTA      — ДРУГАЯ delta: серийная корреляция соседних раундов внутри
#                  симулятора. Тоже 0, пока не откалибрована на демках.
#                  Две разные величины с одним именем — не путать.
GAMMA_FORM = 0.0
DELTA_MOMENTUM = 0.0
SIM_DELTA = 0.0


# ── Лайв-экономика (§1 Г1): что измерено на фактах, а что ещё нет ─────────────
#
# Три флага добыты проверками Т-* этапа 1 шага 5.5 на разложенных лайв-фактах.
# Полный расчёт по игрокам, числа и таблицы — отчёт
# `_reports/2026-09-25_5.5-этап1_проверки-данных.md`, зонд —
# `examples/probe_live_economy.py`.

# Т-деньги. Содержит ли `money` кадра конца раунда r награду ЗА раунд r.
# ИЗМЕРЕНО: нет. Гипотеза «содержит» требует закупа в долг или из ниоткуда в
# 55 наблюдениях из 70 (79 %), гипотеза «не содержит» — в 1 из 70 (1.4 %).
# Следствие для формулы: в §1 Г1 слагаемое R_i ВКЛЮЧАЕТСЯ (`m_i += R_i`).
MONEY_INCLUDES_REWARD = False

# Т-сходимость. `ct_equip_value` / `t_equip_value` строки раунда r — закуп
# ЭТОГО раунда, не следующего. ИЗМЕРЕНО: пистолетный кадр держит пистолетную
# сумму (4150/4450 при 9350/19250 во втором раунде), оружие килфида спорит с
# закупом предыдущей строки и сходится со своей (3 различающих случая из 3).
# Следствие: `Eq_j` в §1 Г2 берётся из строки САМОГО раунда j.
EQUIP_VALUE_IS_OWN_ROUND = True

# Т-мёртвые. `equip_value` мёртвого игрока. ИЗМЕРЕНО: ровно 0, 62 строки из 62,
# NULL не встречается; «последнее живое значение» опровергнуто (0 совпадений
# из 23 сравнимых). На `b_i` не влияет — там стоит множитель `alive_i`, — но
# правило зафиксировано, чтобы ноль не приняли за «поле не пришло».
EQUIP_VALUE_OF_DEAD = 0

# Счётчик поражений подряд L после победы: 'reset' — в ноль, 'decay' — минус
# один. НЕ ИЗМЕРЕНО: в корпусе нет ни одной команды, которая проиграла бы
# ПОСЛЕ победы внутри серии поражений, а значит оба режима дают одни и те же
# числа. Значение взято по правилам CS2 (счётчик убывает на шаг, а не
# обнуляется) и ЖДЁТ ПОДТВЕРЖДЕНИЯ на полной карте — держим его здесь явно,
# а не зашитым в формулу, ровно поэтому.
LOSS_RESET_MODE = "decay"

# Сама лестница поражений (1400 + 500·min(L−1, 4)) на фактах ПОДТВЕРЖДЕНА:
# без неё нарушений становится 5 из 70 вместо 1, с обрезкой на +2 — 2 из 70.
# Строки «+800 проигравшим T при заложенной бомбе» и «3500 за Target_Bombed /
# Bomb_Defused» корпус НЕ РАЗЛИЧАЕТ (1 из 70 в обе стороны) — они остаются на
# правилах CS2, не на измерении.


# ── Линии, по которым печатаем цены ───────────────────────────────────────────
# Реальные линии придут от бука (ЭТАП 4); это просто сетка для витрины.
#
# Почему сетка тоталов обрывается на 24.5. В MR12 регламент даёт максимум
# 13 + 11 = 24 раунда, а счёт 12:12 уходит в овертайм, который добавляет сразу
# минимум 4 раунда. Значит тоталов 25, 26 и 27 НЕ СУЩЕСТВУЕТ вовсе, и линии
# 24.5 и 27.5 — это одна и та же ставка «будет овертайм». Печатать их по
# отдельности значит делать вид, что рынков больше, чем есть.
TOTAL_LINES = (20.5, 21.5, 22.5, 23.5, 24.5)
HANDICAP_LINES = (-6.5, -4.5, -2.5, -1.5, 1.5, 2.5, 4.5, 6.5)


@dataclass(frozen=True)
class StrengthConfig:
    """Параметры расчёта силы пары. Передаются в strength.* явно."""

    lambda_rounds: float = LAMBDA_ROUNDS
    rounds_per_map: float = ROUNDS_PER_MAP
    neutral_prior: float = NEUTRAL_PRIOR
    p_min: float = P_MIN
    p_max: float = P_MAX
    gamma_form: float = GAMMA_FORM
    delta_momentum: float = DELTA_MOMENTUM


DEFAULT = StrengthConfig()


# ── Лайв-прогноз раунда: все коэффициенты §1-§2 спецификации ───────────────────
#
# Одно место на всю математику `SPEC_LIVE_P_ROUND` (rev 25). Держать их здесь, а
# не внутри формул, нужно не для красоты: каждое из этих чисел — СТАРТОВЫЙ
# АПРИОР, который будет калиброваться (§6), и `config_hash` обязан меняться
# вместе с ними. Иначе в журнале смешаются строки, посчитанные разной
# математикой, и подгонка будет считать их однородными.
#
# ⚠ `gamma_form` ниже (0.25, §1 Г9) — НЕ то же самое, что модульная
# `GAMMA_FORM = 0.0` выше. Та относится к ЗАМОРОЖЕННОЙ пред-матчевой формуле
# _STATE, где форма выключена; эта — вес формы в лайв-логите. Имена похожи,
# величины разные, поэтому лайв-конфиг живёт отдельным объектом.

@dataclass(frozen=True)
class LiveConfig:
    """Коэффициенты лайв-модели. Ни одного числа внутри формул — только здесь."""

    # Г1 экономика
    g_eco: float = 2.5             # фулл против эко ≈ +2.2 логита
    e_mid: float = 10000.0         # середина перехода «форс → фулл», $
    e_scale: float = 3500.0        # ширина перехода, $
    cap_ct: float = 5500.0         # полный закуп игрока CT, $
    cap_t: float = 5000.0          # полный закуп игрока T, $

    # Г2 дуэли
    kap: float = 1.2               # численное преимущество: в 5v4 следующий кил 0.567
    omega: float = 0.5             # влияние закупа на дуэль
    tau: float = 0.35              # априорный разброс дуэльной силы (логит)
    att: float = 0.5               # доля «чистой перестрелки» в исходе раунда

    # Г3/Г4 теневые: пишутся, в p_round не входят
    eta: float = 0.0               # вес чистоты раунда
    delta_mom: float = 0.0         # вес момента

    # Г7 конверсия после закладки (описательная)
    pp0: float = 0.9
    pp1: float = 0.55

    # Г8 сила пятёрки до матча
    lambda_str: float = 100.0      # усадка силы пятёрки по выборке, раундов
    c_w: float = 2.19              # перевод c_prior в дуэльную шкалу: theta0 = c/(att·c_w)

    # Г9 форма игрока
    gamma_form: float = 0.25       # вес формы в логите (НЕ модульная GAMMA_FORM = 0)
    pop_adr: float = 75.0          # популяционное среднее ADR
    pop_kast: float = 0.72         # популяционное среднее KAST, доля
    lambda_pop_adr: float = 150.0  # усадка базы ADR к популяции, раундов
    lambda_pop_kast: float = 225.0 # усадка базы KAST к популяции, раундов
    t_adr: float = 6.0             # разброс истинной формы, ADR
    t_kast: float = 0.04           # разброс истинной формы, KAST
    lambda_adr: float = 267.0      # усадка отклонения ADR, раундов
    lambda_kast: float = 126.0     # усадка отклонения KAST, раундов
    rounds_short_window: int = 500 # < этого — окно базы 180 дней вместо 90

    # §2 обрезки
    p_round_min: float = 0.03      # p_round зажимается симметрично
    p_round_max: float = 0.97
    p_base_min: float = P_MIN      # база для будущих раундов — прежние [0.20, 0.80]
    p_base_max: float = P_MAX

    # Г1, флаги из этапа 1 (измерены на фактах, см. выше)
    money_includes_reward: bool = MONEY_INCLUDES_REWARD
    loss_reset_mode: str = LOSS_RESET_MODE


LIVE = LiveConfig()

# Теневые метрики Г9: метрика → (шум за раунд S, разброс истинной формы T_k).
# Λ_k = (S / T_k)² считается на месте, чтобы две величины не разъехались.
# S и T_k здесь ПРОВИЗОРНЫ (§1 Г9), и это единственная причина держать их
# отдельной таблицей: их заменят целиком, а не по одной.
SHADOW_METRICS = {
    "flash_assists": (0.28, 0.02),
    "assists":       (0.45, 0.03),
    "trades":        (0.35, 0.02),
    "entry_kills":   (0.29, 0.02),
    "entry_deaths":  (0.29, 0.02),
    "multikills":    (0.34, 0.02),
}

# Версия лайв-модели. Меняется вместе с ФОРМУЛАМИ; коэффициенты стережёт
# config_hash. Две разные вещи: по version видно, какой код считал строку,
# по hash — какими числами.
#
# live-p_round-2 (2026-10-03) — правки П2 и П3 по итогам первого живого
# овертайма (матч 2398243 / de_cache, 2026-09-27/28). Обе меняют ЧИСЛА, а не
# только диагностику, поэтому строки журнала версии -1 и -2 сравнивать нельзя:
#   П2 — расписание сторон в овертайме: на входе в ОТ стороны НЕ меняются
#        (наблюдено). Правка задевает не только живой ОТ: ветка `p_ot` считает
#        овертайм с нужной расстановкой уже на любой карте, идущей к 12:12,
#        то есть e_total и p_map поехали на всех картах.
#   П3 — правило окончания карты считает порог текущего овертайма, а не 13.
LIVE_MODEL_VERSION = "live-p_round-2"


def live_config_hash(cfg: LiveConfig = LIVE,
                     shadow: dict | None = None) -> str:
    """
    Отпечаток всех чисел лайв-модели — в журнал, рядом с каждой строкой.

    Это не расчёт модели, а подпись набора значений: поэтому функция живёт
    здесь, у самих значений, и не может отстать от них при правке. Теневые
    метрики входят в подпись: они попадают в `form_shadow_json`, и сравнивать
    строки, посчитанные разными S / T_k, нельзя.
    """
    import hashlib
    import json

    payload = {f.name: getattr(cfg, f.name) for f in fields(cfg)}
    payload["_shadow"] = {k: list(v) for k, v in
                          sorted((shadow or SHADOW_METRICS).items())}
    blob = json.dumps(payload, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(blob.encode()).hexdigest()[:12]
